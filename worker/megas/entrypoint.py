"""Product entrypoint for the `megas` executable.

Bare `megas` authenticates and pairs the machine when needed, then starts
Megas. Advanced commands continue to use the existing argparse CLI. Service
and watchdog launchers are redirected to the same unified Local + optional-
cloud runtime used interactively.
"""

from __future__ import annotations

import asyncio
import os
import sys
from pathlib import Path

from megas.config import load_config
from megas.unified_runtime import UnifiedMegasRuntime


def _start_args(argv: list[str]) -> tuple[bool, bool]:
    """Return (matched, foreground) for the simple start surfaces."""
    if not argv:
        return True, False
    if argv[0] == "start":
        remaining = argv[1:]
    elif len(argv) >= 2 and argv[:2] == ["worker", "start"]:
        remaining = argv[2:]
    else:
        return False, False
    unknown = [item for item in remaining if item != "--foreground"]
    if unknown:
        raise SystemExit(f"Unsupported start option(s): {' '.join(unknown)}")
    return True, "--foreground" in remaining


def _ensure_startup_identity(config):
    """Complete the product sign-in and Worker pairing before first start."""
    if config.is_paired:
        return config

    # Reuse the established device-authorization flow. It opens a Megas link,
    # waits for website approval, stores the Worker credential, and binds the
    # approving account to this exact machine.
    from megas.cli.main import _ensure_paired

    return _ensure_paired(config)


def _write_unified_worker_boot_script(service) -> Path:
    """Generate the login/autostart script with the unified composition root."""
    boot = service.state_root() / "boot_worker.py"
    root = str(service.package_root())
    home = str(service.default_config_path().parent)
    boot.write_text(
        "# Auto-generated by Megas. Do not edit.\n"
        "from __future__ import annotations\n"
        "import os\n"
        "import sys\n"
        f"sys.path.insert(0, {root!r})\n"
        f"os.environ['MEGAS_HOME'] = {home!r}\n"
        f"os.environ['PYTHONPATH'] = {root!r} + os.pathsep + os.environ.get('PYTHONPATH', '')\n"
        "from megas.entrypoint import _run_service\n"
        "\n"
        "if __name__ == '__main__':\n"
        "    _run_service()\n",
        encoding="utf-8",
    )
    try:
        os.chmod(boot, 0o600)
    except OSError:
        pass
    return boot


def _install_service_hooks():
    import megas.service as service

    service.WorkerRuntime = UnifiedMegasRuntime
    service.write_worker_boot_script = lambda: _write_unified_worker_boot_script(service)
    return service


def _run_unified_start(*, foreground: bool) -> None:
    service = _install_service_hooks()
    from megas.cli.main import _start_managed, acquire_instance_lock

    acquire_instance_lock()
    config = _ensure_startup_identity(load_config())
    if foreground:
        print("Megas is running in the foreground. Press Ctrl+C to stop.")
        try:
            asyncio.run(UnifiedMegasRuntime(config).start_forever())
        except KeyboardInterrupt:
            print("Megas stopped.")
        return

    # _start_managed reuses the patched service module, so newly generated
    # login/autostart scripts also launch the unified runtime.
    status = _start_managed()
    pid = status.get("pid")
    watchdog_pid = status.get("watchdog_pid")
    cloud = "configured" if config.is_paired else "not configured"
    suffix = f", watchdog PID {watchdog_pid}" if watchdog_pid else ""
    print(f"Megas started (PID {pid}{suffix}).")
    print(
        f"Routes: Local starting · Cloud {cloud} · "
        "Tailscale available after explicit Serve setup."
    )


def _run_service() -> None:
    """Reuse mature daemon lifecycle with the unified runtime class."""
    service = _install_service_hooks()
    service.run_service(load_config())


def _run_watchdog() -> None:
    """Ensure watchdog restarts regenerate the unified Worker boot script."""
    service = _install_service_hooks()
    service.run_watchdog()


def main(argv: list[str] | None = None) -> None:
    args = list(sys.argv[1:] if argv is None else argv)

    matched, foreground = _start_args(args)
    if matched:
        _run_unified_start(foreground=foreground)
        return

    if args in (["worker", "run-service"], ["run-service"]):
        _run_service()
        return

    if args in (["worker", "run-watchdog"], ["run-watchdog"]):
        _run_watchdog()
        return

    if args == ["control"]:
        from megas.cli.main import acquire_instance_lock, cmd_control

        acquire_instance_lock()
        cmd_control()
        return

    from megas.cli.main import main as legacy_main

    legacy_main(args)


__all__ = ["main"]


if __name__ == "__main__":
    main()
